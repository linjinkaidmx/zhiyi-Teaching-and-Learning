/** 反查索引：别名 → 标准知识点，加速匹配 */
const ALIAS_INDEX = (() => {
  const m = new Map()
  Object.entries(KNOWLEDGE_ALIASES).forEach(([std, aliases]) => {
    aliases.forEach((a) => {
      if (!m.has(a)) m.set(a, std)
    })
  })
  return m
})()

/**
 * 两个知识点写法的匹配得分（四档）
 *   10 - 精确相等
 *    8 - 别名等价（任一方在对方的别名表里）
 *    5 - 双向包含（长写法包含短写法，视为同域）
 *    0 - 无关
 */
export function matchScore(a, b) {
  if (!a || !b) return 0
  const x = a.trim()
  const y = b.trim()
  if (!x || !y) return 0
  if (x === y) return 10

  // 别名等价：x 是 y 的别名，或 y 是 x 的别名
  if (ALIAS_INDEX.get(x) === y || ALIAS_INDEX.get(y) === x) return 8
  if ((KNOWLEDGE_ALIASES[x] || []).includes(y)) return 8
  if ((KNOWLEDGE_ALIASES[y] || []).includes(x)) return 8

  // 包含匹配：要求短的一方至少 4 个字，避免「导数」匹配所有带导数的词导致过泛
  const [short, long] = x.length <= y.length ? [x, y] : [y, x]
  if (short.length >= 4 && long.includes(short)) return 5
  return 0
}

/** 一个知识点与一组知识点的最高匹配分 */
export function bestMatch(kp, kpList) {
  let best = 0
  for (const k of kpList || []) {
    const s = matchScore(kp, k)
    if (s > best) best = s
  }
  return best
}
